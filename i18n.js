  // 名詞按鈕（[[x]]、[[x.pt]]、光環標籤）→ 對照表的條目 id
  var GL_OF = { 'four.rush': 'four', 'fourThree.pt': 'points', 'doubleThree.pt': 'points', 'doubleFour.pt': 'points', 'vcf.road': 'vcf', indirect: 'direct' };
  function glossaryId(name) {
    name = String(name || '');
    if (GL_OF[name]) return GL_OF[name];
    var base = name.split('.')[0];
    for (var i = 0; i < GLOSSARY.length; i++) if (GLOSSARY[i].id === base) return base;
    return null;
  }

  // ai.js 的 isForbidden 回傳中文種類名 → 名詞鍵
  var FORBIDDEN_TERM = { '三三': 'doubleThree', '四四': 'doubleFour', '長連': 'overline' };

  function detect() {
    var saved = null;
    try { saved = localStorage.getItem(LKEY); } catch (e) { saved = null; }
    if (saved === 'zh-TW' || saved === 'en') return saved;
    var nav = (navigator.languages && navigator.languages[0]) || navigator.language || '';
    return /^zh/i.test(nav) ? 'zh-TW' : 'en';
  }
  var lang = detect();

  function raw(key) {
    var d = DICT[lang];
    if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
    if (Object.prototype.hasOwnProperty.call(DICT['zh-TW'], key)) return DICT['zh-TW'][key];
    return key;
  }
  function fill(s, params) {
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? String(params[k]) : m; });
  }
  function termText(name) { return raw('term.' + name); }

  // 單複數：params.n 是 1、而目前語言的字典有 key + '.one' 時改用它（多半只有英文有；中文有 review.partial.one（區間 a–b 只有一步時要換句）、
  // review.losingDetail.one、review.stillLosing.one（這條路只有一步時不說「再下 1 步…一共 1 步」））
  function pick(key, params) {
    var d = DICT[lang];
    if (params && Number(params.n) === 1 && d && Object.prototype.hasOwnProperty.call(d, key + '.one')) return key + '.one';
    return key;
  }

  // [[x]]、[[x.pt]]、[[x:字]]（規格 AK：「字」是畫面上的字，x 是連到哪個名詞）
  var TERM_RE = /\[\[([\w.]+)(?::([^\]]*))?\]\]/g;
  function t(key, params) {
    return fill(raw(pick(key, params)), params).replace(TERM_RE, function (m, name, text) { return text != null ? text : termText(name); });
  }

  // 一顆名詞按鈕：data-term＝名詞（舊的，規則說明面板的圖）、data-gl＝名詞對照表的條目（app.js 用事件委派開對照表）
  function termButton(name, text) {
    var b = document.createElement('button');
    b.type = 'button';
    b.className = 'term';
    b.setAttribute('data-term', String(name).split('.')[0]);
    var gl = glossaryId(name);
    if (gl) b.setAttribute('data-gl', gl);
    b.textContent = text != null ? text : termText(name);
    return b;
  }

  // 把 [[term]] 做成可點的名詞按鈕（app.js 用事件委派開名詞對照表）
  function node(key, params) {
    var s = fill(raw(pick(key, params)), params);
    var frag = document.createDocumentFragment();
    var re = new RegExp(TERM_RE.source, 'g'), last = 0, m;
    while ((m = re.exec(s))) {
      if (m.index > last) frag.appendChild(document.createTextNode(s.slice(last, m.index)));
      frag.appendChild(termButton(m[1], m[2]));
      last = re.lastIndex;
    }
    if (last < s.length) frag.appendChild(document.createTextNode(s.slice(last)));
    return frag;
  }

  // 句子裡的名詞（[[x]] 或 [[x.pt]] 的 x）：提醒列行尾的「？」開第一個名詞的說明（第十四批，W 第 1 條）
  function terms(key, params) {
    var s = fill(raw(pick(key, params)), params), out = [], re = new RegExp(TERM_RE.source, 'g'), m;
    while ((m = re.exec(s))) out.push(m[1].split('.')[0]);
    return out;
  }

  // data-i18n="key" → 文字；data-i18n-attr="aria-label:key;title:key" → 屬性；
  // data-i18n-terms="key" → 文字，裡面的名詞做成可點的按鈕（規格 AK：關於頁的名詞）
  function apply(root) {
    (root || document).querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    (root || document).querySelectorAll('[data-i18n-terms]').forEach(function (el) {
      el.textContent = '';
      el.appendChild(node(el.getAttribute('data-i18n-terms')));
    });
    (root || document).querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var kv = pair.split(':');
        if (kv.length === 2) el.setAttribute(kv[0].trim(), t(kv[1].trim()));
      });
    });
  }

  function setLang(l) {
    lang = l === 'en' ? 'en' : 'zh-TW';
    try { localStorage.setItem(LKEY, lang); } catch (e) { /* 不存 */ }
  }

  window.I18N = {
    DICT: DICT,
    ROMAJI: ROMAJI,
    t: t,
    node: node,
    terms: terms,
    termText: termText,
    apply: apply,
    has: function (key) { return Object.prototype.hasOwnProperty.call(DICT['zh-TW'], key); },
    getLang: function () { return lang; },
    setLang: setLang,
    forbiddenName: function (f) { return FORBIDDEN_TERM[f] ? termText(FORBIDDEN_TERM[f]) : String(f || ''); },
    // 規格 AK：禁手種類當成可點的名詞（給 node() 的參數；t() 一樣只換成字）
    forbiddenTerm: function (f) { return FORBIDDEN_TERM[f] ? '[[' + FORBIDDEN_TERM[f] + ']]' : String(f || ''); },
    termButton: termButton,
    GLOSSARY: GLOSSARY,
    glossaryId: glossaryId
  };
